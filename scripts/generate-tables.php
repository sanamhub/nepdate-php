<?php

declare(strict_types=1);

/**
 * Compiles shared/data/calendar/bs-calendar.json into src/Internal/CalendarTable.php
 * (spec/ALGORITHM.md §1-2). JSON is read only here, never at runtime (CONTRIBUTING.md).
 *
 *   php scripts/generate-tables.php           regenerate
 *   php scripts/generate-tables.php --check   fail if the committed file would change
 */

$root = dirname(__DIR__);
$jsonPath = $root . '/shared/data/calendar/bs-calendar.json';
$outPath = $root . '/src/Internal/CalendarTable.php';

$data = json_decode((string) file_get_contents($jsonPath), true, 512, JSON_THROW_ON_ERROR);

$minYear = (int) $data['min_year'];
$maxYear = (int) $data['max_year'];
$years = $maxYear - $minYear + 1;
$lengths = $data['month_lengths'];

$packed = [];
$yearStart = [0];
$total = 0;
for ($i = 0; $i < $years; $i++) {
    $year = (string) ($minYear + $i);
    if (!isset($lengths[$year])) {
        fwrite(STDERR, "missing month_lengths for year $year\n");
        exit(1);
    }
    $months = $lengths[$year];
    if (count($months) !== 12) {
        fwrite(STDERR, "year $year does not have 12 months\n");
        exit(1);
    }
    $p = 0;
    $sum = 0;
    foreach ($months as $m => $len) {
        $len = (int) $len;
        if ($len < 29 || $len > 32) {
            fwrite(STDERR, "year $year month " . ($m + 1) . " length $len out of range 29..32\n");
            exit(1);
        }
        $p |= ($len - 29) << (2 * $m);
        $sum += $len;
    }
    $packed[] = $p;
    $total += $sum;
    $yearStart[] = $total;
}

$maxSerial = $total - 1;

$packedLiteral = implode(', ', $packed);
$yearStartLiteral = implode(', ', $yearStart);

$source = $data['source'];
$generatedFrom = sprintf(
    '%s @ %s',
    $source['repo'],
    substr((string) $source['commit'], 0, 12)
);

$php = <<<PHP
<?php

declare(strict_types=1);

namespace NepDate\Internal;

// DO NOT EDIT. Generated by scripts/generate-tables.php from
// shared/data/calendar/bs-calendar.json ($generatedFrom).
// spec/ALGORITHM.md §1-2 defines every constant below.

/**
 * @internal
 */
final class CalendarTable
{
    public const int MIN_YEAR = $minYear;
    public const int MAX_YEAR = $maxYear;
    public const int YEARS = $years;
    public const int TOTAL_DAYS = $total;
    public const int MAX_SERIAL = $maxSerial;
    public const int EPOCH_UNIX_DAYS = -45920;
    public const int EPOCH_WEEKDAY = 4;

    /** @var list<int> Two bits per month (length - 29), index 0 = MIN_YEAR. */
    public const array PACKED = [$packedLiteral];

    /** @var list<int> Cumulative day count at the start of each year; index YEARS = TOTAL_DAYS. */
    public const array YEAR_START = [$yearStartLiteral];
}

PHP;

$current = is_file($outPath) ? file_get_contents($outPath) : null;

if (in_array('--check', $argv, true)) {
    if ($current !== $php) {
        fwrite(STDERR, "src/Internal/CalendarTable.php is out of date; run: composer codegen\n");
        exit(1);
    }
    fwrite(STDOUT, "src/Internal/CalendarTable.php matches shared/data/calendar/bs-calendar.json\n");
    exit(0);
}

if (!is_dir(dirname($outPath))) {
    mkdir(dirname($outPath), 0777, true);
}
file_put_contents($outPath, $php);
fwrite(STDOUT, "wrote src/Internal/CalendarTable.php ($years years, $total days)\n");
